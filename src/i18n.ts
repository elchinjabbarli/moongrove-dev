const DICTS: Record<string, Dict> = { en: EN, tr: TR };

export let lang: 'en' | 'tr' = 'en';

export function initLang(): void {
  const nav = typeof navigator !== 'undefined' ? navigator.language || '' : 'en';
  lang = nav.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = (DICTS[lang] && DICTS[lang][key]) || EN[key] || key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  }
  return s;
}

export function chapterName(ch: number): string {
  const arr = lang === 'tr' ? CHAPTERS_TR : CHAPTERS_EN;
  return arr[ch % arr.length];
}
